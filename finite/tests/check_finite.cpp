// Checks of kategoria/finite: finite categories, their families, constructions and properties.
//
// - Families against their counts in closed form: the ordinal n has n(n + 1)/2 arrows; the subsets of 3 have 3³ = 27;
//   the divisors of 12 = 2²·3 have 6 × 3 = 18; FinSet up to n has Σ k^m; Δ up to [n] has Σ C(m + k + 1, m + 1).
// - validate() accepts each, and names the place where a table that is not associative fails.
// - Constructions: the opposite of the opposite is the category; products, sums, slices and coslices by their counts.
// - Properties: in FinSet up to 2 the monic arrows are the 8 injections, the epic the 5 surjections, the invertible the
//   4 bijections; initial and terminal objects; classes of isomorphic objects, skeletons, components.
// - Generators: the ordinal n is generated by its n − 1 covers, the subsets of 3 by their 12; a group by few.

#include <kategoria/finite/category.hpp>

#include <calx/verification/check.hpp>
#include <morphe/algebra/finite_group.hpp>

#include <string>
#include <vector>

using namespace kategoria::finite;

static Category group_of(const morphe::algebra::FiniteGroup& G) { return group(G.order(), G.table, G.name); }

int main() {
  calx::verification::Suite s;
  auto count = [&](const std::string& what, const Category& C, std::size_t objects, std::size_t arrows) {
    const auto v = validate(C);
    s.require(what + ": " + std::to_string(objects) + " objects, " + std::to_string(arrows) + " arrows, a category", C.objects.size() == objects && C.size() == arrows && v.holds(),
              std::to_string(C.objects.size()) + " objects, " + std::to_string(C.size()) + " arrows; " + v.reason);
  };
  count("the ordinal 4", chain(4), 4, 10);
  count("the discrete category on 3", discrete(3), 3, 3);
  count("the subsets of 3", subsets(3), 8, 27);
  count("the divisors of 12", divisors(12), 6, 18);
  count("FinSet up to 2", finset(2), 3, 11);
  count("FinSet up to 3", finset(3), 4, 60);
  count("Δ up to [2]", simplex(2), 3, 31);
  count("Δ up to [3]", simplex(3), 4, 121);
  count("the symmetric group on 3, one object", group_of(morphe::algebra::symmetric(3)), 1, 6);
  count("(ℤ/6, ×), one object", multiplicative(6), 1, 6);

  // A table that is not associative: e the identity, a a = b, a b = a, b a = e, b b = a; (a a) b = a and a (a b) = b.
  const Category magma = monoid({"e", "a", "b"}, {0, 1, 2, 1, 2, 1, 2, 0, 1}, "a magma");
  const auto bad = validate(magma);
  s.require("validate: a table that is not associative fails, at three named arrows", bad.fails() && bad.reason.find("associative") != std::string::npos && !bad.piece("at").empty() && !bad.piece("left").empty(), bad.reason);
  Category broken = chain(3);
  broken.identity[1] = broken.arrow("0≤1");
  s.require("validate: an identity that is no arrow from its object to itself fails", validate(broken).fails());
  bool refused = false;
  try {
    preorder({"a", "b", "c"}, {{1, 1, 0}, {0, 1, 1}, {0, 0, 1}});
  } catch (const std::invalid_argument&) {
    refused = true;
  }
  s.require("preorder: a relation that is not transitive is refused", refused);

  // Constructions.
  const Category F = finset(2);
  const Category FF = opposite(opposite(F));
  s.require("opposite: the opposite is a category, and the opposite of the opposite has the first's table", validate(opposite(F)).holds() && FF.table == F.table && FF.arrows[5].dom == F.arrows[5].dom);
  count("the product of the ordinals 2 and 3", product(chain(2), chain(3)), 6, 18);
  count("the sum of the ordinals 2 and 3", coproduct(chain(2), chain(3)), 5, 9);
  const Within S = slice(chain(4), 2);
  count("the slice of the ordinal 4 over 2", S.category, 3, 6);
  s.require("slice: its terminal object is the identity", terminal_objects(S.category).size() == 1 && S.objects[terminal_objects(S.category)[0]] == chain(4).identity[2]);
  const Within T = coslice(chain(4), 1);
  count("the coslice of the ordinal 4 under 1", T.category, 3, 6);
  s.require("coslice: its initial object is the identity", initial_objects(T.category).size() == 1 && T.objects[initial_objects(T.category)[0]] == chain(4).identity[1]);
  // An arrow of the slice into g : b → 2 is any u into b, so there are Σ_b (functions b → 2)(arrows into b) = 1·1 + 2·3 + 4·7.
  count("the slice of FinSet up to 2 over 2", slice(F, F.object("2")).category, 7, 35);
  const Within sub = full_subcategory(F, {F.object("1"), F.object("2")});
  count("the full subcategory of FinSet on 1 and 2", sub.category, 2, 1 + 2 + 1 + 4);

  // Properties.
  std::size_t monos = 0, epis = 0, isos = 0;
  for (Index f = 0; f < F.size(); f++) monos += monic(F, f).holds(), epis += epic(F, f).holds(), isos += is_iso(F, f);
  s.require("FinSet up to 2: 8 monic arrows (the injections), 5 epic (the surjections), 4 invertible", monos == 8 && epis == 5 && isos == 4,
            std::to_string(monos) + ", " + std::to_string(epis) + ", " + std::to_string(isos));
  const auto not_monic = monic(F, F.arrow("[2→1|00]"));
  s.require("monic: the function 2 → 1 is not, and the two arrows it identifies are named", not_monic.fails() && !not_monic.piece("at").empty(), not_monic.reason);
  s.require("initial and terminal: 0 and 3 in the ordinal 4; ∅ and 1 in FinSet; none in a group",
            initial_objects(chain(4)) == std::vector<Index>{0} && terminal_objects(chain(4)) == std::vector<Index>{3} && initial_objects(F) == std::vector<Index>{F.object("0")} &&
                terminal_objects(F) == std::vector<Index>{F.object("1")} && initial_objects(group_of(morphe::algebra::cyclic(3))).empty());
  const Category iso = preorder({"a", "b"}, {{1, 1}, {1, 1}}, "the walking isomorphism");
  s.require("the walking isomorphism: thin, a groupoid, one class of objects, a skeleton of one arrow",
            is_thin(iso) && is_groupoid(iso) && isomorphism_classes(iso) == std::vector<Index>{0, 0} && skeleton(iso).category.size() == 1);
  s.require("thin, groupoid, discrete: the ordinal is thin and no groupoid; a group is a groupoid and not thin; the discrete is all three",
            is_thin(chain(3)) && !is_groupoid(chain(3)) && is_groupoid(group_of(morphe::algebra::symmetric(3))) && !is_thin(group_of(morphe::algebra::symmetric(3))) && is_discrete(discrete(4)) && is_groupoid(discrete(4)));
  s.require("components: the sum of two ordinals has two; FinSet has one", components(coproduct(chain(2), chain(3))) == std::vector<Index>{0, 0, 1, 1, 1} && components(F) == std::vector<Index>{0, 0, 0});

  // Generators.
  auto generates = [](const Category& C) {
    const auto in = generated(C, generators(C));
    return std::all_of(in.begin(), in.end(), [](char c) { return c == 1; });
  };
  s.require("generators: the ordinal 5 by its 4 covers", generators(chain(5)).size() == 4 && generates(chain(5)));
  s.require("generators: the subsets of 3 by their 12 covers", generators(subsets(3)).size() == 12 && generates(subsets(3)));
  s.require("generators: ℤ/5 by one arrow, the symmetric group on 3 by two", generators(group_of(morphe::algebra::cyclic(5))).size() == 1 && generators(group_of(morphe::algebra::symmetric(3))).size() == 2);
  s.require("generators: FinSet up to 3 and Δ up to [3] are generated by what is found", generates(finset(3)) && generates(simplex(3)));
  const Category C5 = chain(5);
  const auto part = generated(C5, {C5.arrow("0≤1"), C5.arrow("1≤2")});
  s.require("generated: two covers of the ordinal 5 generate the 5 identities and 3 arrows", std::count(part.begin(), part.end(), 1) == 8);
  s.require("Δ up to [2] is generated by its 8 faces and degeneracies, which is the basis it is given", generators(simplex(2)).size() == 8 && generates(simplex(2)), std::to_string(generators(simplex(2)).size()));
  s.require("the product of the ordinals 3 and 4 is generated by 2·4 + 3·3 = 17 arrows, each a cover in one and an identity in the other", generators(product(chain(3), chain(4))).size() == 2 * 4 + 3 * 3 && generates(product(chain(3), chain(4))));
  Category bare = simplex(2);
  bare.basis.clear();
  s.require("without a basis, a category with retractions still gets arrows that generate it", generates(bare) && !generators(bare).empty());
  return s.done();
}
