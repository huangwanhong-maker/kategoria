// The verification of a resource type: every law it must satisfy, each answered by a method whose verdict says what it
// establishes, and allocations checked as morphisms.
//
// Methods, and what their verdicts mean (the infrastructure's survey Evolutionary heterogeneous resource allocation, §1.9
// and Part IV §6 (c)):
//
//   construction   the law holds for every type built from the primitive quantity semirings by products, by a closure
//                  theorem the verdict names: the primitives are commutative monoids with their natural orders compatible
//                  (ℕ, (1/q)ℕ, ℚ≥0, ℤ, ℚ under +; {0, 1} under ∨; ℚ≥0 under max), and products of ordered commutative monoids,
//                  ordered componentwise, are ordered commutative monoids (equational and inequational laws are preserved
//                  by products: Birkhoff 1935; Bloom 1976); the order generated by conversions and disposal is compatible
//                  with combination because it is the least precongruence containing them. A proof for every such type.
//   generators     a law that is a homomorphism (a conservation law, a monotone, a price) is checked on each generating
//                  process; a proof for every bundle (algebra.hpp, verify_law).
//   finite model   exhaustively on a truncation of the type (finite.hpp); a proof for that model only. A counterexample
//                  found there refutes the property outright, since the model's elements are elements of the type and its
//                  order is the type's order restricted.
//   search         bounded search with a witness, replayed, or a monotone refuting; else undecided (algebra.hpp).
//
// Nothing here samples: a sampled check is evidence, never proof, and belongs to a library that draws at random.
//
// An allocation of a pool to recipients is the morphism pool → r₁ ⊗ … ⊗ rₙ: lawful when each part and their combination are
// valid and the pool converts into the combination (equal to it where nothing may be disposed of and nothing converted);
// regrouping the recipients changes nothing, by the monoid laws.

